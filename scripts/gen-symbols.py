#!/usr/bin/env python3
"""Symbol + line table for the stop screen (runtime/src/core/crash.cpp).

    gen-symbols.py <stage1.elf> <out.S>        write the table as assembly (section .neko_symbols)
    gen-symbols.py --verify <stage1.elf> <final.elf>

The kernel is linked twice: stage 1 without the table, then again with it. The
table lives in its own segment after .bss, so the code addresses do not move —
--verify checks exactly that.

Function names of C# code are printed C#-style (Nekotia.OS.Commands.Crash);
file names are relative to the repository root (kernel/Shell/Commands.neko).
"""
import os
import re
import subprocess
import sys

BASE = 0xFFFFFFFF80000000
ROOT = os.getcwd()


def run(*args):
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def pretty(name):
    name = name.replace('(anonymous namespace)::', '')
    # Drop the parameter list: the first '(' outside template brackets.
    depth = 0
    for i, c in enumerate(name):
        if c == '<':
            depth += 1
        elif c == '>':
            depth -= 1
        elif c == '(' and depth == 0 and not name.startswith('operator', max(0, i - 8)):
            name = name[:i]
            break
    if '::' in name and not name.startswith('neko::'):
        name = name.replace('::', '.')  # generated from C#
    return name


def functions(elf):
    result = []
    for line in run('llvm-nm', '--defined-only', '-n', '-C', '--print-size', elf).splitlines():
        parts = line.split(None, 3)
        if len(parts) == 4:
            addr, size, kind, name = parts
        elif len(parts) == 3:
            (addr, kind, name), size = parts, '0'
        else:
            continue
        if kind not in 'tTwW':
            continue
        a = int(addr, 16)
        if a >= BASE:
            result.append((a, int(size, 16), pretty(name)))
    result.sort()
    return result


def relative(path):
    path = os.path.normpath(path)
    if path.startswith(ROOT + os.sep):
        return path[len(ROOT) + 1:]
    return path


def lines(elf):
    rows = []
    dirs, files, current = {}, {}, None
    for line in run('llvm-dwarfdump', '--debug-line', elf).splitlines():
        if line.startswith('debug_line['):
            dirs, files, current = {}, {}, None
            continue
        m = re.match(r'include_directories\[\s*(\d+)\] = "(.*)"', line)
        if m:
            dirs[int(m.group(1))] = m.group(2)
            continue
        m = re.match(r'file_names\[\s*(\d+)\]:', line)
        if m:
            current = int(m.group(1))
            files[current] = {'name': '', 'dir': 0}
            continue
        m = re.match(r'\s+name: "(.*)"', line)
        if m and current is not None:
            files[current]['name'] = m.group(1)
            continue
        m = re.match(r'\s+dir_index: (\d+)', line)
        if m and current is not None:
            files[current]['dir'] = int(m.group(1))
            continue
        m = re.match(r'(0x[0-9a-f]+)\s+(\d+)\s+\d+\s+(\d+)\s+\d+\s+\d+\s+\d+\s*(.*)$', line)
        if m:
            addr, ln, fidx, flags = int(m.group(1), 16), int(m.group(2)), int(m.group(3)), m.group(4)
            if addr < BASE:
                continue
            if 'end_sequence' in flags or ln == 0:
                rows.append((addr, 0, ''))
                continue
            f = files.get(fidx, {'name': '?', 'dir': 0})
            name = f['name']
            path = name if os.path.isabs(name) else os.path.join(dirs.get(f['dir'], ''), name)
            rows.append((addr, ln, relative(path)))
    rows.sort(key=lambda r: r[0])
    compact = []
    for r in rows:
        if compact and compact[-1][0] == r[0]:
            compact[-1] = r  # several rows at one address: the last one wins
        elif not compact or compact[-1][1:] != r[1:]:
            compact.append(r)
    return compact


def asm_string(s):
    out = []
    for b in s.encode('utf-8'):
        if b in (0x22, 0x5C):
            out.append('\\' + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def generate(elf, out):
    funcs = functions(elf)
    rows = lines(elf)
    strings, blob = {}, []
    size = 0

    def intern(s):
        nonlocal size
        if s not in strings:
            strings[s] = size
            blob.append(s)
            size += len(s.encode('utf-8')) + 1
        return strings[s]

    file_index = {}
    for _, ln, path in rows:
        if ln and path not in file_index:
            file_index[path] = len(file_index)
    file_offsets = [intern(p) for p in file_index]
    func_entries = [(a, s, intern(n)) for a, s, n in funcs]

    with open(out, 'w') as f:
        f.write('/* generated by scripts/gen-symbols.py — do not edit */\n')
        f.write('.section .neko_symbols, "a"\n.balign 8\n.global neko_symtab\nneko_symtab:\n')
        f.write(f'    .quad {len(func_entries)}, {len(rows)}, {len(file_offsets)}\n')
        f.write('    .quad neko_sym_functions, neko_sym_lines, neko_sym_files, neko_sym_strings\n')
        f.write('.balign 8\nneko_sym_functions:\n')
        for a, s, n in func_entries:
            f.write(f'    .quad {a:#x}\n    .long {min(s, 0xFFFFFFFF)}, {n}\n')
        f.write('.balign 4\nneko_sym_lines:\n')
        for a, ln, path in rows:
            f.write(f'    .long {a - BASE:#x}, {ln}, {file_index.get(path, 0)}\n')
        f.write('.balign 4\nneko_sym_files:\n')
        for off in file_offsets:
            f.write(f'    .long {off}\n')
        f.write('neko_sym_strings:\n')
        for s in blob:
            f.write(f'    .asciz {asm_string(s)}\n')
        f.write('\n.section .note.GNU-stack, "", @progbits\n')
    print(f'symbols: {len(func_entries)} functions, {len(rows)} line rows, {len(file_offsets)} files')


def verify(stage1, final):
    a = [(x[0], x[2]) for x in functions(stage1)]
    b = [(x[0], x[2]) for x in functions(final)]
    if a != b:
        diff = next((x, y) for x, y in zip(a, b) if x != y) if len(a) == len(b) else (len(a), len(b))
        sys.exit(f'gen-symbols: code moved between link passes: {diff}')


if __name__ == '__main__':
    if len(sys.argv) == 4 and sys.argv[1] == '--verify':
        verify(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 3:
        generate(sys.argv[1], sys.argv[2])
    else:
        sys.exit(__doc__)
