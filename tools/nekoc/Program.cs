using Nekotia.Compiler;
using Nekotia.Compiler.Sugar;

// nekoc — Nekotia C# → C++ transpiler.
//
//   nekoc build   [--config nekotia.json] [--format text|json]
//   nekoc check   [--config nekotia.json] [--format text|json]
//   nekoc desugar <file.neko>
//   nekoc version

var argList = args.ToList();
if (argList.Count == 0 || argList[0] is "-h" or "--help" or "help")
{
    PrintUsage();
    return argList.Count == 0 ? 1 : 0;
}

var command = argList[0];
argList.RemoveAt(0);

string configPath = TakeOption(argList, "--config") ?? "nekotia.json";
string format = TakeOption(argList, "--format") ?? "text";

switch (command)
{
    case "version":
        Console.WriteLine($"nekoc {typeof(Driver).Assembly.GetName().Version?.ToString(3)}");
        return 0;

    case "desugar":
    {
        string? outPath = TakeOption(argList, "--out");
        if (argList.Count != 1)
        {
            Console.Error.WriteLine("usage: nekoc desugar <file.neko> [--out file.cs]");
            return 1;
        }
        var csharp = Desugarer.Desugar(File.ReadAllText(argList[0]));
        if (outPath is null)
        {
            Console.Write(csharp);
            return 0;
        }
        // For the IDE project: diagnostics map back to the .neko file (the desugarer keeps line numbers).
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outPath))!);
        var source = Path.GetFullPath(argList[0]).Replace("\\", "\\\\");
        var content = $"// <auto-generated> nekoc desugar\n#line 1 \"{source}\"\n{csharp}";
        if (!File.Exists(outPath) || File.ReadAllText(outPath) != content)
            File.WriteAllText(outPath, content);
        return 0;
    }

    case "build":
    case "check":
        ProjectConfig config;
        try
        {
            config = ProjectConfig.Load(configPath);
        }
        catch (Exception e)
        {
            Console.Error.WriteLine($"nekoc: error: {e.Message}");
            return 1;
        }

        var result = Driver.Run(config, emit: command == "build");
        if (format == "json")
            Console.WriteLine(result.Diagnostics.ToJson());
        else
            result.Diagnostics.PrintText(Console.Error);

        if (command == "build" && result.Success && format != "json")
            Console.WriteLine($"nekoc: generated {string.Join(", ", result.WrittenFiles)}");
        return result.Success ? 0 : 1;

    default:
        Console.Error.WriteLine($"nekoc: unknown command '{command}'");
        PrintUsage();
        return 1;
}

static string? TakeOption(List<string> list, string name)
{
    int i = list.IndexOf(name);
    if (i < 0 || i + 1 >= list.Count)
        return null;
    var value = list[i + 1];
    list.RemoveRange(i, 2);
    return value;
}

static void PrintUsage()
{
    Console.WriteLine("""
        nekoc — Nekotia C# → C++ kernel transpiler

        usage:
          nekoc build   [--config nekotia.json] [--format text|json]   transpile the kernel to C++
          nekoc check   [--config nekotia.json] [--format text|json]   only report diagnostics
          nekoc desugar <file.neko> [--out file.cs]                    print a .neko file as plain C#
          nekoc version
        """);
}
