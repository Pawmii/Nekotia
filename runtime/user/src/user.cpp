int64_t read_line(uint8_t* buffer, uint64_t capacity) {
    if (capacity == 0) return -1;
    uint64_t n = 0;
    for (;;) {
        uint8_t c;
        int64_t got = read(&c, 1);
        if (got <= 0) {
            buffer[n] = 0;
            return n ? int64_t(n) : -1;
        }
        if (c == '\n') break;
        if (n + 1 < capacity) buffer[n++] = c;
    }
    buffer[n] = 0;
    return int64_t(n);
}

// ---------------------------------------------------------------- heap
//
// Address-ordered free list with splitting and coalescing; grows by asking the kernel for pages.

namespace {

struct alignas(16) Block {
    uint64_t size;  // payload bytes (multiple of 16)
    uint32_t magic;
    uint32_t free;
    Block* next;    // address order (all blocks of one chunk, then the next chunk)
};
constexpr uint32_t kMagic = 0x4E454B4F;
constexpr uint64_t kChunk = 64 * 1024;

Block* g_blocks = nullptr;
uint64_t g_used = 0, g_total = 0;

bool grow(uint64_t payload) {
    uint64_t bytes = payload + sizeof(Block);
    bytes = bytes < kChunk ? kChunk : (bytes + 4095) & ~uint64_t(4095);
    int64_t at = sys::call(kAlloc, bytes);
    if (at < 0) return false;
    auto* b = reinterpret_cast<Block*>(at);
    b->size = bytes - sizeof(Block);
    b->magic = kMagic;
    b->free = 1;
    b->next = nullptr;
    // Chunks come from increasing addresses: append, merging with the last block when adjacent.
    Block* last = g_blocks;
    while (last && last->next) last = last->next;
    if (!last) g_blocks = b;
    else if (last->free && reinterpret_cast<uint8_t*>(last + 1) + last->size == reinterpret_cast<uint8_t*>(b))
        last->size += bytes;
    else last->next = b;
    g_total += bytes;
    return true;
}

}  // namespace

void* alloc(uint64_t size) {
    Locked g(g_heap_lock);
    if (size == 0) size = 1;
    size = (size + 15) & ~uint64_t(15);
    for (int attempt = 0; attempt < 2; ++attempt) {
        for (Block* b = g_blocks; b; b = b->next) {
            if (!b->free || b->size < size) continue;
            if (b->size >= size + sizeof(Block) + 16) {  // split
                auto* rest = reinterpret_cast<Block*>(reinterpret_cast<uint8_t*>(b + 1) + size);
                rest->size = b->size - size - sizeof(Block);
                rest->magic = kMagic;
                rest->free = 1;
                rest->next = b->next;
                b->next = rest;
                b->size = size;
            }
            b->free = 0;
            g_used += b->size;
            return b + 1;
        }
        if (!grow(size)) return nullptr;
    }
    return nullptr;
}

void* alloc_zeroed(uint64_t size) {
    void* p = alloc(size);
    if (p) __builtin_memset(p, 0, size);
    return p;
}

void free(void* block) {
    if (!block) return;
    Locked g(g_heap_lock);
    Block* b = static_cast<Block*>(block) - 1;
    if (b->magic != kMagic || b->free) crash::panic_at("heap: invalid or double free", nullptr, 0, nullptr);
    b->free = 1;
    g_used -= b->size;
    for (Block* c = g_blocks; c && c->next;) {  // coalesce adjacent free neighbours
        Block* n = c->next;
        if (c->free && n->free && reinterpret_cast<uint8_t*>(c + 1) + c->size == reinterpret_cast<uint8_t*>(n)) {
            c->size += sizeof(Block) + n->size;
            c->next = n->next;
        } else {
            c = n;
        }
    }
}

uint64_t heap_used() { return g_used; }
uint64_t heap_total() { return g_total; }

