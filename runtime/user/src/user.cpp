void write_codepoint(uint32_t cp) {
    Locked g(g_out_lock);
    if (cp < 0x80) {
        put(uint8_t(cp));
    } else if (cp < 0x800) {
        put(uint8_t(0xC0 | (cp >> 6)));
        put(uint8_t(0x80 | (cp & 0x3F)));
    } else if (cp < 0x10000) {
        put(uint8_t(0xE0 | (cp >> 12)));
        put(uint8_t(0x80 | ((cp >> 6) & 0x3F)));
        put(uint8_t(0x80 | (cp & 0x3F)));
    } else {
        put(uint8_t(0xF0 | (cp >> 18)));
        put(uint8_t(0x80 | ((cp >> 12) & 0x3F)));
        put(uint8_t(0x80 | ((cp >> 6) & 0x3F)));
        put(uint8_t(0x80 | (cp & 0x3F)));
    }
}

void write_hex(uint64_t value) {
    Locked g(g_out_lock);
    static constexpr char kDigits[] = "0123456789abcdef";
    put_str("0x");
    bool started = false;
    for (int shift = 60; shift >= 0; shift -= 4) {
        unsigned digit = (value >> shift) & 0xF;
        if (digit || started || shift == 0) {
            put(static_cast<uint8_t>(kDigits[digit]));
            started = true;
        }
    }
}

void write_udec(uint64_t v) {
    Locked g(g_out_lock);
    put_udec(v);
}

void write_dec(int64_t v) {
    Locked g(g_out_lock);
    if (v < 0) {
        put('-');
        put_udec(uint64_t(0) - uint64_t(v));
    } else {
        put_udec(uint64_t(v));
    }
}

void write_size(uint64_t bytes) {
    Locked g(g_out_lock);
    static constexpr const char* kUnits[] = {"B", "KiB", "MiB", "GiB", "TiB"};
    int unit = 0;
    uint64_t divisor = 1;
    while (bytes / divisor >= 1024 && unit < 4) {
        divisor *= 1024;
        ++unit;
    }
    uint64_t tenths = (bytes / divisor) * 10 + ((bytes % divisor) * 10 + divisor / 2) / divisor;
    put_udec(tenths / 10);
    if (unit > 0 && tenths % 10 != 0 && tenths < 1000) {
        put('.');
        put_udec(tenths % 10);
    }
    put(' ');
    put_str(kUnits[unit]);
}

void write_float(double v, int32_t decimals) {
    Locked g(g_out_lock);
    if (v != v) return put_str("NaN");
    if (v < 0 || (v == 0 && __builtin_signbit(v))) {
        put('-');
        v = -v;
    }
    if (v > 1.8e19) return put_str("∞");
    if (decimals < 0) decimals = 0;
    if (decimals > 9) decimals = 9;
    uint64_t scale = 1;
    for (int i = 0; i < decimals; ++i) scale *= 10;
    uint64_t whole = uint64_t(v);
    uint64_t frac = uint64_t((v - double(whole)) * double(scale) + 0.5);
    if (frac >= scale) ++whole, frac -= scale;
    put_udec(whole);
    if (decimals == 0) return;
    put('.');
    for (uint64_t d = scale / 10; d > 1 && frac < d; d /= 10) put('0');
    put_udec(frac);
}

