[[noreturn]] void die(const char* kind, const char* type, const char* message, const char* file, int32_t line,
                      const char* function) {
    using namespace neko::user;
    write("\x1b[91m");
    write(kind);
    if (type) {
        write(type);
        write(": ");
    }
    write(message ? message : "");
    write("\x1b[0m\n");
    if (function) {
        write("   at ");
        write(function);
        if (file) {
            write(" in ");
            write(file);
            write(":");
            write_dec(line);
        }
        write("\n");
    }
    exit(134);
}

