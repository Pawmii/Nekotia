// memcpy/memset/memmove/memcmp: runtime/src/freestanding/libc.cpp is linked into every program.
extern "C" {
void __cxa_pure_virtual() { neko::crash::panic_at("pure virtual call", nullptr, 0, nullptr); }
}

void* operator new(size_t n) { return neko::user::alloc(n); }
void* operator new[](size_t n) { return neko::user::alloc(n); }
void operator delete(void* p) noexcept { neko::user::free(p); }
void operator delete[](void* p) noexcept { neko::user::free(p); }
void operator delete(void* p, size_t) noexcept { neko::user::free(p); }
void operator delete[](void* p, size_t) noexcept { neko::user::free(p); }

using Constructor = void (*)();
extern "C" Constructor __init_array_start[];
extern "C" Constructor __init_array_end[];

// Called by crt0.S with what the kernel put in rdi/rsi.
namespace {
neko::user::Tls g_main_tls;
}

extern "C" [[noreturn]] void neko_user_start(int argc, uint8_t** argv) {
    neko::user::set_tls(&g_main_tls);  // before any C# code: scope guards need it
    neko::user::g_argc = argc;
    neko::user::g_argv = argv;
    for (Constructor* c = __init_array_start; c != __init_array_end; ++c) (*c)();
    neko::user::exit(neko_user_main(argc, argv));
}
