namespace neko::user {

// Thread-local block: %fs:0 points at it (set_tls). Holds the thread's try/catch state.
struct Tls {
    Tls* self;
    exc::State exc;
};

struct ThreadControl {  // layout used by neko_user_thread_entry (crt0.S)
    ThreadEntry entry;   // 0
    uint64_t arg;        // 8
    uint8_t* stack;      // 16
    uint32_t tid;        // 24
    volatile uint32_t done;  // 28
    Tls tls;
};

inline void set_tls(Tls* t) {
    t->self = t;
    sys::call(31, reinterpret_cast<uint64_t>(t));
}
static_assert(__builtin_offsetof(ThreadControl, done) == 28, "crt0.S writes done at 28");

}  // namespace neko::user

extern "C" void neko_user_thread_entry();  // crt0.S
extern "C" void neko_user_thread_run(neko::user::ThreadControl* t) {
    neko::user::set_tls(&t->tls);
    t->entry(t->arg);
}

namespace neko::exc {
State* state() {
    user::Tls* t;
    __asm__("mov %%fs:0, %0" : "=r"(t));
    return &t->exc;
}
}  // namespace neko::exc

