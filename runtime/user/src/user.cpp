// ---- stdout buffer: flushed at '\n', when full, before reading, at exit
uint8_t g_out[512];
uint64_t g_out_len = 0;

void flush_locked() {
    if (g_out_len) sys::call(kWrite, 1, reinterpret_cast<uint64_t>(g_out), g_out_len);
    g_out_len = 0;
}

void put(uint8_t c) {  // g_out_lock held
    g_out[g_out_len++] = c;
    if (c == '\n' || g_out_len == sizeof(g_out)) flush_locked();
}

void flush() {
    Locked g(g_out_lock);
    flush_locked();
}

void put_str(const char* s) {
    if (!s) s = "(null)";
    while (*s) put(static_cast<uint8_t>(*s++));
}

void put_udec(uint64_t value) {
    char buf[21];
    int i = 0;
    do {
        buf[i++] = static_cast<char>('0' + value % 10);
        value /= 10;
    } while (value);
    while (i) put(static_cast<uint8_t>(buf[--i]));
}

